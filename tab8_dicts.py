def get_site_revs_t8(s_name, use_exec_26=True):
    d = SITES_DETAILED_DB[s_name]
    revs = [d["rev_shamel"][i] + d["other_rev"][i] for i in range(5)]
    r26 = (d["exec_rev_2026"] if use_exec_26 else d["rev_shamel"][5]) + d["other_rev"][5]
    revs.append(r26)
