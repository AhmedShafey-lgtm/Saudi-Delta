def aggregate_projects(keys_list):
    agg = {k: [0.0]*6 for k in ["rev_shamel", "other_rev", "salaries", "direct_cost", "maint_veh", "rent_trans", "tools_cons", "ga_exp", "fin_exp", "dep_exp"]}
