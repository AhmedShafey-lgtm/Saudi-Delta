def compute_summary(col):
    rev = df_main.loc[0, col]
    cogs = df_main.loc[1:7, col].sum()
    gp = rev - cogs
    ga = df_main.loc[8, col]
    ebit = gp - ga
    fin = df_main.loc[9, col]
    other = df_main.loc[10, col]
    ebt = ebit - fin + other
    return rev, cogs, gp, ga, ebit, ebt

