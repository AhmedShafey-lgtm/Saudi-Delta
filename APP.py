# دالة تنسيق الأرقام والأسطر داخل الجداول المالية
def fmt_val(val, is_pct=False):
    if val is None or val == "":
        return ""
    if is_pct:
        return f"{val:.1f}%"
    if val < 0:
        return f"({abs(val):,.0f})"
    return f"{val:,.0f}"

def build_styled_table(rows_spec, columns):
    """
    rows_spec: list of tuples (row_type, label, [v1, v2, v3, ...])
    row_type in: 'section', 'item', 'subtotal', 'pct', 'total'
    """
    formatted_rows = []
    row_types = []
    for r_type, label, vals in rows_spec:
        row_types.append(r_type)
        if r_type == 'section':
            formatted_rows.append([label] + [""] * (len(columns) - 1))
        elif r_type == 'pct':
            formatted_rows.append([label] + [fmt_val(v, is_pct=True) for v in vals])
        else:
            formatted_rows.append([label] + [fmt_val(v, is_pct=False) for v in vals])
            
    df = pd.DataFrame(formatted_rows, columns=columns)
    
    def apply_row_styles(row):
        idx = row.name
        rt = row_types[idx]
        if rt == 'section':
            return ['background-color: #1E3A8A; color: #FFFFFF; font-weight: bold; font-size: 1.02rem;'] * len(row)
        elif rt == 'subtotal':
            return ['background-color: #DBEAFE; color: #1E3A8A; font-weight: bold; border-top: 1px solid #93C5FD; border-bottom: 1px solid #93C5FD;'] * len(row)
        elif rt == 'pct':
            return ['background-color: #F3F4F6; color: #374151; font-weight: 600; font-style: italic;'] * len(row)
        elif rt == 'total':
            return ['background-color: #DCFCE7; color: #14532D; font-weight: bold; font-size: 1.05rem; border-top: 2px solid #166534; border-bottom: 2px double #166534;'] * len(row)
        else:
            return ['background-color: #FFFFFF; color: #111827;'] * len(row)

    return df.style.apply(apply_row_styles, axis=1)

